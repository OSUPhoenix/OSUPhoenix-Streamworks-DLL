        // Replace these placeholder arrays with your generated output.
        //
        // The three arrays must always be regenerated together — _idParts and
        // _secParts are encoded against _xorKey, so all three must match.

        // XOR key — the decoding key. Keep the same length as your longest encoded value.
        private static readonly byte[] _xorKey = new byte[]
        {
            0x00 // PLACEHOLDER — replace with generated output
        };

        // Google OAuth Client ID, XOR-encoded against _xorKey
        private static readonly byte[] _idParts = new byte[]
        {
            0x00 // PLACEHOLDER — replace with generated output
        };

        // Google OAuth Client Secret, XOR-encoded against _xorKey
        private static readonly byte[] _secParts = new byte[]
        {
            0x00 // PLACEHOLDER — replace with generated output
        };

        // ── DPAPI entropy ─────────────────────────────────────────────────────
        // A static salt used with Windows DPAPI when encrypting the Google
        // refresh token. Must be identical in every distributed DLL build —
        // these bytes are part of the decryption key. If you change them,
        // all existing encrypted refresh tokens become unreadable and users
        // will need to re-authorize.
        //
        // Generate once, never change. At least 16 bytes, more is fine.
        // Any random byte sequence works — use a GUID or random number generator,
        // not something guessable.
        internal static readonly byte[] DpapiEntropy = new byte[]
        {
            0x00 // PLACEHOLDER — replace with generated output
        };

        // ── Public accessors ──────────────────────────────────────────────────
        // These are the only things OmsOAuthManager ever calls.
        // The XOR decoding happens here at call time — the plaintext string
        // exists in memory only for the duration of the API call that needs it.

        internal static string ClientId     => Decode(_idParts,  _xorKey);
        internal static string ClientSecret => Decode(_secParts, _xorKey);

        // ── XOR decode ────────────────────────────────────────────────────────
        // Reconstructs the original string by XOR-ing each byte against the
        // repeating key. Standard symmetric XOR — same operation encodes and decodes.
        private static string Decode(byte[] data, byte[] key)
        {
            if (data == null || data.Length == 0 || key == null || key.Length == 0)
                return "";

            byte[] result = new byte[data.Length];
            for (int i = 0; i < data.Length; i++)
                result[i] = (byte)(data[i] ^ key[i % key.Length]);

            return System.Text.Encoding.UTF8.GetString(result);
        }
    }
}
