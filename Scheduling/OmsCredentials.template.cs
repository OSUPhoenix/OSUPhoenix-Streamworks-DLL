//
// WHY XOR ENCODING:
//   Strings stored as plain literals in a .NET assembly are readable with any
//   IL decompiler (ILSpy, dnSpy, etc.) — they appear verbatim in the string
//   heap. XOR-encoding the credential bytes means the decompiler sees integer
//   arrays and math, not a Client ID or Secret string. It's not unbreakable,
//   but it stops casual inspection and automated credential scrapers that look
//   for string patterns.
//
// WHY NOT AES OR RSA HERE:
//   Those require a key, and the key would have the same problem — it would
//   have to live in the binary too. XOR with a split key is the standard
//   approach for this specific problem (protecting credentials in distributed
//   binaries). The real protection comes from the combination of:
//     1. XOR obfuscation (stops casual extraction)
//     2. DPAPI on the refresh token (stops cross-machine token theft)
//     3. .gitignore on this source file (stops credential leaks via repo)

